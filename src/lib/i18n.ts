const DICTS: Record<Lang, Record<DictKey, string>> = { en, zh };

/** Translates a key, interpolating `{placeholders}`. */
export function translate(
  lang: Lang,
  key: DictKey,
  vars?: Record<string, string | number>
): string {
  const table = DICTS[lang] ?? en;
  let value: string = table[key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

export function t(key: DictKey, vars?: Record<string, string | number>): string {
  return translate(getLang(), key, vars);
}

export interface I18n {
  lang: Lang;
  locale: string;
  t: (key: DictKey, vars?: Record<string, string | number>) => string;
  setLang: (lang: Lang) => void;
  toggle: () => void;
}

/** Subscribes the component tree to language changes. */
export function useI18n(): I18n {
  const lang = useSyncExternalStore(
    (listener) => onLangChange(() => listener()),
    getLang,
    getLang
  );
  return {
    lang,
    locale: localeTag(lang),
    t: (key, vars) => translate(lang, key, vars),
    setLang: setActiveLang,
    toggle: () => setActiveLang(lang === 'en' ? 'zh' : 'en'),
  };
}
